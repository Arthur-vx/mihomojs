const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const net = require('node:net')

const domainURL = 'https://raw.githubusercontent.com/pluwen/china-domain-allowlist/main/allow-list.sorl'
const ipURL = 'https://raw.githubusercontent.com/Loyalsoldier/clash-rules/release/cncidr.txt'

function convertDomains(text) {
  const domains = []
  for (const raw of text.replace(/^\uFEFF/, '').split(/\r?\n/)) {
    const line = raw.trim()
    if (!line || line.startsWith(';') || line.startsWith('[')) continue
    // SwitchyOmega 内网 IPv4 通配已由脚本的私网 CIDR 覆盖。
    if (/^[\d.*]+$/.test(line)) continue
    if (!/^(?:\*\.)?[a-z0-9*-]+(?:\.[a-z0-9*-]+)+$/i.test(line)) throw new Error(`Unsupported domain condition: ${line}`)
    domains.push(line.startsWith('*.') ? `+.${line.slice(2).toLowerCase()}` : line.toLowerCase())
  }
  return [...new Set(domains)]
}

function convertCIDRs(text) {
  if (!/^payload:\s*$/m.test(text)) throw new Error('Expected a Clash payload list')
  const cidrs = []
  for (const line of text.split(/\r?\n/)) {
    if (!line.trim() || line.trim().startsWith('#') || /^payload:\s*$/.test(line)) continue
    const match = /^\s*-\s*['"]?([0-9a-fA-F.:]+\/\d+)['"]?\s*$/.exec(line)
    if (!match) throw new Error(`Unsupported CIDR line: ${line}`)
    const [address, prefix] = match[1].split('/')
    const version = net.isIP(address)
    if (!version || Number(prefix) > (version === 4 ? 32 : 128)) throw new Error(`Invalid CIDR: ${match[1]}`)
    cidrs.push(match[1])
  }
  return [...new Set(cidrs)]
}

async function main() {
  const responses = await Promise.all([domainURL, ipURL].map(url => fetch(url, { signal: AbortSignal.timeout(30000) })))
  for (const response of responses) if (!response.ok) throw new Error(`Download failed: ${response.status} ${response.url}`)
  const [domainsText, cidrsText] = await Promise.all(responses.map(response => response.text()))
  const domains = convertDomains(domainsText)
  const cidrs = convertCIDRs(cidrsText)
  if (domains.length < 100 || cidrs.length < 1000) throw new Error('Unexpectedly short rule sources; existing snapshot not modified')
  const sha256 = text => crypto.createHash('sha256').update(text).digest('hex')
  const snapshot = {
    updated: new Date().toISOString(),
    sources: { domains: { url: domainURL, sha256: sha256(domainsText) }, cidrs: { url: ipURL, sha256: sha256(cidrsText) } },
    domains, cidrs,
  }
  const scriptPath = path.join(__dirname, '..', 'Script-CN-Direct.js')
  const source = fs.readFileSync(scriptPath, 'utf8')
  const start = '// BEGIN CN RULE SNAPSHOT (generated by scripts/refresh-cn-direct-rules.js)'
  const end = '// END CN RULE SNAPSHOT'
  if (!source.includes(start) || !source.includes(end)) throw new Error('Snapshot markers missing')
  const updated = source.slice(0, source.indexOf(start) + start.length) +
    `\nconst CN_DIRECT_SNAPSHOT = ${JSON.stringify(snapshot, null, 2)}\n` + source.slice(source.indexOf(end))
  fs.writeFileSync(scriptPath, updated)
  console.log(`Updated ${domains.length} domain rules and ${cidrs.length} CIDRs`)
}

if (require.main === module) main().catch(error => { console.error(error.message); process.exitCode = 1 })
module.exports = { convertDomains, convertCIDRs }
